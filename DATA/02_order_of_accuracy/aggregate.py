#!/usr/bin/env python3
# ===========================================================================
#  Collect the per-curve results of the scaling_2026 campaign into the tables
#  the paper needs.
#
#  Reads  DATA/scaling_2026/results/<curve>.json  (one per finished curve)
#  Writes DATA/scaling_2026/results/
#           A_orders.txt  B_orders.txt  C_orders.txt   one row per curve
#           orders_table.tex                           paper table, block A/B/C
#           summary.json                               everything, machine-readable
#           MISSING.txt                                curves not yet finished
#
#  usage:  aggregate.py [--block A|B|C]
# ===========================================================================
import os, json, glob, argparse
import campaign as C


def load():
    done, missing = {}, []
    for c in C.all_curves():
        fn = os.path.join(C.RES_ROOT, f"{c['name']}.json")
        if os.path.isfile(fn):
            with open(fn) as f:
                done[c['name']] = json.load(f)
        else:
            missing.append(c['name'])
    return done, missing


def key_cols(c):
    """the columns that identify a curve inside its block."""
    if c['block'] == 'A':
        return [c['ep_type'], c['gas'], str(c['fd_order']), c['dir'], c['mesh']]
    if c['block'] == 'B':
        return [C.B_ABBR[c['scheme']] + str(c['weno_order']), c['gas'], c['dir'], c['mesh']]
    return [c['diffusion'], str(c['fd_order']), c['mesh']]


HEAD = {'A': ['ep_type', 'gas', 'fd', 'dir', 'mesh'],
        'B': ['scheme', 'gas', 'dir', 'mesh'],
        'C': ['diffusion', 'fd', 'mesh']}


def expected(c):
    return c['fd_order'] if c['block'] in ('A', 'C') else c['weno_order']


def write_orders(block, done):
    cs = [c for c in C.curves_of(block) if c['name'] in done]
    head = HEAD[block]
    w = [max(len(h), *(len(key_cols(c)[i]) for c in cs)) if cs else len(h)
         for i, h in enumerate(head)]
    lines = [f'# scaling_2026 -- block {block} ({C.BLOCK_DIR[block]})',
             '# fitted convergence order, least squares over the points above 1e-12',
             '# nref = expected order; runs = completed/total points on the ladder',
             '#']
    hdr = '# ' + '  '.join(f'{h:{w[i]}s}' for i, h in enumerate(head))
    lines.append(hdr + '    pL1     pL2   pLinf   nref   runs')
    for c in cs:
        d = done[c['name']]
        k = key_cols(c)
        row = '  ' + '  '.join(f'{k[i]:{w[i]}s}' for i in range(len(head)))
        f = d['fit']
        ok = sum(1 for r in d['runs'] if 'error' not in r)
        lines.append(row + f"  {f['L1']:7.3f} {f['L2']:7.3f} {f['Linf']:7.3f}"
                           f"   {expected(c):4d}  {ok:2d}/{len(d['runs']):2d}")
    path = os.path.join(C.RES_ROOT, f'{block}_orders.txt')
    with open(path, 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    return path, len(cs)


def write_tex(done):
    """paper table: observed L2 order per scheme, one column per mesh family,
       averaged over the advection directions (they must agree; the spread is
       printed so a direction-dependent defect cannot hide inside the mean)."""
    out = ['% generated by DATA/02_order_of_accuracy/aggregate.py',
           '\\begin{tabular}{llrrr}', '\\hline',
           'scheme & order & real cart. & fake cart. & wavy \\\\', '\\hline']
    groups = {}
    for c in C.curves_of('A') + C.curves_of('B') + C.curves_of('C'):
        if c['name'] not in done:
            continue
        if c['block'] == 'A':
            g = (f"{c['ep_type']}-{c['gas']}", c['fd_order'])
        elif c['block'] == 'B':
            g = (f"{C.B_ABBR[c['scheme']].upper()}{c['weno_order']}-{c['gas']}", c['weno_order'])
        else:
            g = (c['diffusion'], c['fd_order'])
        groups.setdefault(g, {}).setdefault(c['mesh'], []).append(done[c['name']]['fit']['L2'])
    for (label, order), bymesh in groups.items():
        cells = []
        for m in C.MESHES:
            v = bymesh.get(m)
            if not v:
                cells.append('--')
            elif len(v) == 1:
                cells.append(f'{v[0]:.2f}')
            else:
                cells.append(f'{sum(v)/len(v):.2f}')
        out.append(f"{label} & {order} & " + ' & '.join(cells) + ' \\\\')
    out += ['\\hline', '\\end{tabular}']
    path = os.path.join(C.RES_ROOT, 'orders_table.tex')
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--block', choices=list(C.BLOCK_DIR))
    args = ap.parse_args()

    done, missing = load()
    os.makedirs(C.RES_ROOT, exist_ok=True)
    for block in ([args.block] if args.block else ['A', 'B', 'C']):
        path, n = write_orders(block, done)
        print(f'  block {block}: {n:4d} curves -> {path}')
    with open(os.path.join(C.RES_ROOT, 'summary.json'), 'w') as f:
        json.dump(done, f, indent=1)
    print('  tex    :', write_tex(done))
    with open(os.path.join(C.RES_ROOT, 'MISSING.txt'), 'w') as f:
        f.write('\n'.join(missing) + ('\n' if missing else ''))
    print(f'  done {len(done)}/{len(C.all_curves())} curves, {len(missing)} missing')


if __name__ == '__main__':
    main()
